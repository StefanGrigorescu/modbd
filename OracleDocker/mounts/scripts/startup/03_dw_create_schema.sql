SET SERVEROUTPUT ON;

-- Switch to DW PDB
ALTER SESSION SET CONTAINER = eshop_dw;

-- Check if user eshop_dw_user exists
DECLARE
    user_exists NUMBER := 0;
BEGIN
    SELECT COUNT(*)
    INTO user_exists
    FROM dba_users
    WHERE username = 'ESHOP_DW_USER';

    IF user_exists = 0 THEN
        -- Create DW schema
        EXECUTE IMMEDIATE '
            CREATE USER eshop_dw_user IDENTIFIED BY dw_password
            -- DEFAULT TABLESPACE users
            -- QUOTA UNLIMITED ON users
            ACCOUNT UNLOCK
        ';
        DBMS_OUTPUT.PUT_LINE('dw_create_schema: User schema eshop_dw_user was successfully created.');
    ELSE
        DBMS_OUTPUT.PUT_LINE('dw_create_schema: User schema eshop_dw_user already exists.');
    END IF;
END;
/


DECLARE
    was_role_created NUMBER := 0;
BEGIN
    -- Check if role exists
    SELECT COUNT(*)
    INTO was_role_created
    FROM dba_roles
    WHERE role = 'ESHOP_DW_SYS';

    IF was_role_created = 0 THEN
    -- Create role
        EXECUTE IMMEDIATE 'CREATE ROLE ESHOP_DW_SYS';
        DBMS_OUTPUT.PUT_LINE('dw_create_schema: Role ESHOP_DW_SYS was successfully created.');
    ELSE
        DBMS_OUTPUT.PUT_LINE('dw_create_schema: Role ESHOP_DW_SYS already exists.');
    END IF;
END;
/

-- Grant necessary privileges to the role
BEGIN
    EXECUTE IMMEDIATE 'GRANT CONNECT TO ESHOP_DW_SYS';
    EXECUTE IMMEDIATE 'GRANT RESOURCE TO ESHOP_DW_SYS';
    EXECUTE IMMEDIATE 'GRANT CREATE TABLE TO ESHOP_DW_SYS';
    EXECUTE IMMEDIATE 'GRANT CREATE VIEW TO ESHOP_DW_SYS';
    EXECUTE IMMEDIATE 'GRANT CREATE MATERIALIZED VIEW TO ESHOP_DW_SYS';
