    EXECUTE IMMEDIATE 'GRANT CREATE PROCEDURE TO ESHOP_DW_SYS';
    EXECUTE IMMEDIATE 'GRANT CREATE SEQUENCE TO ESHOP_DW_SYS';
    EXECUTE IMMEDIATE 'GRANT CREATE TRIGGER TO ESHOP_DW_SYS';
    EXECUTE IMMEDIATE 'GRANT CREATE TYPE TO ESHOP_DW_SYS';
    EXECUTE IMMEDIATE 'GRANT QUERY REWRITE TO ESHOP_DW_SYS';
    EXECUTE IMMEDIATE 'GRANT SELECT_CATALOG_ROLE TO ESHOP_DW_SYS';
    EXECUTE IMMEDIATE 'GRANT ALTER SESSION TO ESHOP_DW_SYS';
    EXECUTE IMMEDIATE 'GRANT SELECT ANY DICTIONARY TO ESHOP_DW_SYS';
    EXECUTE IMMEDIATE 'GRANT CREATE PUBLIC DATABASE LINK TO ESHOP_DW_SYS';
    EXECUTE IMMEDIATE 'GRANT CREATE PUBLIC SYNONYM TO ESHOP_DW_SYS';
END;
/

DECLARE
    -- Variables to check existing privileges
    has_eshop_dw_sys_role NUMBER := 0;
    has_dba_role NUMBER := 0;
    has_resource_role NUMBER := 0;
    has_connect_role NUMBER := 0;
    has_create_session NUMBER := 0;
    has_select_any_dictionary NUMBER := 0;
    has_select_all_constraints NUMBER := 0;
    has_select_user_constraints NUMBER := 0;
BEGIN
    -- Check for ESHOP_DW_SYS role
    SELECT COUNT(*) INTO has_eshop_dw_sys_role
    FROM DBA_ROLE_PRIVS
    WHERE GRANTEE = 'ESHOP_DW_USER' AND GRANTED_ROLE = 'ESHOP_DW_SYS';

    -- Check for DBA role
    SELECT COUNT(*) INTO has_dba_role
    FROM DBA_ROLE_PRIVS
    WHERE GRANTEE = 'ESHOP_DW_USER' AND GRANTED_ROLE = 'DBA';

    -- Check for RESOURCE role
    SELECT COUNT(*) INTO has_resource_role
    FROM DBA_ROLE_PRIVS
    WHERE GRANTEE = 'ESHOP_DW_USER' AND GRANTED_ROLE = 'RESOURCE';

    -- Check for CONNECT role
    SELECT COUNT(*) INTO has_connect_role
    FROM DBA_ROLE_PRIVS
    WHERE GRANTEE = 'ESHOP_DW_USER' AND GRANTED_ROLE = 'CONNECT';

    -- Check for CREATE SESSION privilege
    SELECT COUNT(*) INTO has_create_session
    FROM DBA_SYS_PRIVS
    WHERE GRANTEE = 'ESHOP_DW_USER' AND PRIVILEGE = 'CREATE SESSION';

    -- Check for SELECT ANY DICTIONARY privilege
    SELECT COUNT(*) INTO has_select_any_dictionary
    FROM DBA_SYS_PRIVS
    WHERE GRANTEE = 'ESHOP_DW_USER' AND PRIVILEGE = 'SELECT ANY DICTIONARY';

    -- Check for SELECT privilege on SYS.ALL_CONSTRAINTS
    SELECT COUNT(*) INTO has_select_all_constraints
    FROM DBA_TAB_PRIVS
    WHERE GRANTEE = 'ESHOP_DW_USER' AND TABLE_NAME = 'ALL_CONSTRAINTS' AND PRIVILEGE = 'SELECT';

    -- Check for SELECT privilege on SYS.USER_CONSTRAINTS
    SELECT COUNT(*) INTO has_select_user_constraints
    FROM DBA_TAB_PRIVS
    WHERE GRANTEE = 'ESHOP_DW_USER' AND TABLE_NAME = 'USER_CONSTRAINTS' AND PRIVILEGE = 'SELECT';

    -- Conditionally grant ESHOP_DW_SYS role
    IF has_eshop_dw_sys_role = 0 THEN
        EXECUTE IMMEDIATE 'GRANT ESHOP_DW_SYS TO ESHOP_DW_USER';
    END IF;

    -- Conditionally grant DBA role
    IF has_dba_role = 0 THEN
        EXECUTE IMMEDIATE 'GRANT DBA TO ESHOP_DW_USER';
    END IF;

    -- Conditionally grant RESOURCE role
    IF has_resource_role = 0 THEN
        EXECUTE IMMEDIATE 'GRANT RESOURCE TO ESHOP_DW_USER';
    END IF;

    -- Conditionally grant CONNECT role
    IF has_connect_role = 0 THEN
        EXECUTE IMMEDIATE 'GRANT CONNECT TO ESHOP_DW_USER';
    END IF;

    -- Conditionally grant CREATE SESSION privilege
    IF has_create_session = 0 THEN
        EXECUTE IMMEDIATE 'GRANT CREATE SESSION TO ESHOP_DW_USER';
    END IF;

    -- Conditionally grant SELECT ANY DICTIONARY privilege
    IF has_select_any_dictionary = 0 THEN
        EXECUTE IMMEDIATE 'GRANT SELECT ANY DICTIONARY TO ESHOP_DW_USER';
    END IF;

    -- Conditionally grant SELECT privilege on SYS.ALL_CONSTRAINTS
    IF has_select_all_constraints = 0 THEN
        EXECUTE IMMEDIATE 'GRANT SELECT ON SYS.ALL_CONSTRAINTS TO ESHOP_DW_USER';
    END IF;

    -- Conditionally grant SELECT privilege on SYS.USER_CONSTRAINTS
    IF has_select_user_constraints = 0 THEN
        EXECUTE IMMEDIATE 'GRANT SELECT ON SYS.USER_CONSTRAINTS TO ESHOP_DW_USER';
    END IF;

    EXECUTE IMMEDIATE 'GRANT UNLIMITED TABLESPACE to ESHOP_DW_USER';
    
    -- Optional: Log or output the grant actions
    DBMS_OUTPUT.PUT_LINE('dw_create_schema: Necessary privileges were granted to eshop_dw_user.');
END;
/

