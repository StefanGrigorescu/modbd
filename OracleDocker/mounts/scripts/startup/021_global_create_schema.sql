SET SERVEROUTPUT ON;

-- Switch to GLOBAL PDB
ALTER SESSION SET CONTAINER = eshop_global;

-- Check if user eshop_global_user exists
DECLARE
    user_exists NUMBER := 0;
BEGIN
    SELECT COUNT(*)
    INTO user_exists
    FROM dba_users
    WHERE username = 'ESHOP_GLOBAL_USER';

    IF user_exists = 0 THEN
        -- Create GLOBAL schema
        EXECUTE IMMEDIATE '
            CREATE USER eshop_global_user IDENTIFIED BY "GlobalUserPassword123!"
            ACCOUNT UNLOCK
        ';
        DBMS_OUTPUT.PUT_LINE('global_create_schema: User eshop_global_user was successfully created.');
    ELSE
        DBMS_OUTPUT.PUT_LINE('global_create_schema: User eshop_global_user already exists.');
    END IF;
END;
/

-- Check if role eshop_global_sys exists
DECLARE
    role_exists NUMBER := 0;
BEGIN
    SELECT COUNT(*)
    INTO role_exists
    FROM dba_roles
    WHERE role = 'ESHOP_GLOBAL_SYS';

    IF role_exists = 0 THEN
        -- Create role
        EXECUTE IMMEDIATE 'CREATE ROLE ESHOP_GLOBAL_SYS';
        DBMS_OUTPUT.PUT_LINE('global_create_schema: Role ESHOP_GLOBAL_SYS was successfully created.');
    ELSE
        DBMS_OUTPUT.PUT_LINE('global_create_schema: Role ESHOP_GLOBAL_SYS already exists.');
    END IF;
END;
/

-- Grant necessary privileges to the role
BEGIN
    EXECUTE IMMEDIATE 'GRANT CONNECT TO ESHOP_GLOBAL_SYS';
    EXECUTE IMMEDIATE 'GRANT RESOURCE TO ESHOP_GLOBAL_SYS';
    EXECUTE IMMEDIATE 'GRANT CREATE TABLE TO ESHOP_GLOBAL_SYS';
    EXECUTE IMMEDIATE 'GRANT CREATE VIEW TO ESHOP_GLOBAL_SYS';
