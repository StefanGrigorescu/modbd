    EXECUTE IMMEDIATE 'GRANT CREATE SYNONYM TO ESHOP_GLOBAL_SYS';
    EXECUTE IMMEDIATE 'GRANT CREATE PROCEDURE TO ESHOP_GLOBAL_SYS';
    EXECUTE IMMEDIATE 'GRANT CREATE SEQUENCE TO ESHOP_GLOBAL_SYS';
    EXECUTE IMMEDIATE 'GRANT CREATE TRIGGER TO ESHOP_GLOBAL_SYS';
    EXECUTE IMMEDIATE 'GRANT CREATE TYPE TO ESHOP_GLOBAL_SYS';
    EXECUTE IMMEDIATE 'GRANT QUERY REWRITE TO ESHOP_GLOBAL_SYS';
    EXECUTE IMMEDIATE 'GRANT SELECT_CATALOG_ROLE TO ESHOP_GLOBAL_SYS';
    EXECUTE IMMEDIATE 'GRANT ALTER SESSION TO ESHOP_GLOBAL_SYS';
    EXECUTE IMMEDIATE 'GRANT SELECT ANY DICTIONARY TO ESHOP_GLOBAL_SYS';
    EXECUTE IMMEDIATE 'GRANT CREATE PUBLIC DATABASE LINK TO ESHOP_GLOBAL_SYS';
    EXECUTE IMMEDIATE 'GRANT CREATE PUBLIC SYNONYM TO ESHOP_GLOBAL_SYS';
END;
/

