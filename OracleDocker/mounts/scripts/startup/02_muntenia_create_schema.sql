    EXECUTE IMMEDIATE 'GRANT CREATE PROCEDURE TO ESHOP_MUNTENIA_SYS';
    EXECUTE IMMEDIATE 'GRANT CREATE SEQUENCE TO ESHOP_MUNTENIA_SYS';
    EXECUTE IMMEDIATE 'GRANT CREATE TRIGGER TO ESHOP_MUNTENIA_SYS';
    EXECUTE IMMEDIATE 'GRANT CREATE TYPE TO ESHOP_MUNTENIA_SYS';
    EXECUTE IMMEDIATE 'GRANT QUERY REWRITE TO ESHOP_MUNTENIA_SYS';
    EXECUTE IMMEDIATE 'GRANT SELECT_CATALOG_ROLE TO ESHOP_MUNTENIA_SYS';
    EXECUTE IMMEDIATE 'GRANT ALTER SESSION TO ESHOP_MUNTENIA_SYS';
    EXECUTE IMMEDIATE 'GRANT SELECT ANY DICTIONARY TO ESHOP_MUNTENIA_SYS';
    EXECUTE IMMEDIATE 'GRANT CREATE PUBLIC DATABASE LINK TO ESHOP_MUNTENIA_SYS';
    EXECUTE IMMEDIATE 'GRANT CREATE PUBLIC SYNONYM TO ESHOP_MUNTENIA_SYS';
    EXECUTE IMMEDIATE 'GRANT UNLIMITED TABLESPACE TO ESHOP_MUNTENIA_SYS';
END;
